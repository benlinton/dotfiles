# MACOS VOICE CONTROL CHEATSHEET
# Enable: System Settings > Accessibility > Voice Control
# Tutorial: Voice Control settings > Commands... > Open Tutorial
# Listening indicator appears in the menu bar with a microphone icon.
# Use superwhisper for free-form text entry; use Voice Control for UI control.

## START AND STOP LISTENING
"Go to sleep" / "Stop listening"        # Pause listening (commands ignored until resumed)
"Wake up" / "Start listening"           # Resume listening
"Stop listening <device-name>"          # Stop listening on a specific device only

## SHOW GRID AND NUMBERS
"Show numbers"                          # Overlay numbers on every clickable element
"Hide numbers"                          # Dismiss number overlay
"Click <n>"                             # Click numbered element (e.g. "Click 26")
"Show names"                            # Persistent overlay of element names
"Show names once"                       # Names overlay that hides after one use
"Hide names"                            # Dismiss names overlay
"Show grid"                             # Overlay numbered grid on the screen
"Show window grid"                      # Grid limited to the focused window
"Hide grid"                             # Dismiss grid
"<n>"                                   # Drill into grid cell by number
"Click <n>" (in grid)                   # Click center of grid cell n

## UI NAMES AND CLICKING
"Click <name>"                          # Click element by its visible label (e.g. "Click Button")
"Double click <name>"                   # Double-click element
"Right click <name>" / "Control click"  # Open contextual menu
"Long press <name>"                     # Press and hold

## OPENING AND CLOSING APPS
"Open <app>"                            # Launch app (e.g. "Open Notes")
"Quit <app>"                            # Quit app (e.g. "Quit Notes")
"Switch to <app>"                       # Bring app to front
"Hide <app>" / "Hide this"              # Hide current app
"Minimize window" / "Close window"      # Window controls
"Show desktop"                          # Reveal desktop

## SCROLLING
"Scroll up" / "Scroll down"             # Scroll active view
"Scroll left" / "Scroll right"          # Horizontal scroll
"Scroll to top" / "Scroll to bottom"    # Jump to extremes
"Page up" / "Page down"                 # Page-sized scroll

## PRESSING KEYS
"Press return key" / "Press enter key"  # Return / Enter
"Press escape key"                      # Esc
"Press delete key"                      # Delete (backspace)
"Press space key"                       # Space
"Press tab key"                         # Tab
"Press up arrow key"                    # Arrow keys (up/down/left/right)
"Press shift <key>"                     # Modifier + key (e.g. "Press shift one key")
"Press command Z key"                   # Cmd-Z (undo)
"Press command shift three keys"        # Cmd-Shift-3 — full-screen screenshot
"Press command shift four keys"        # Cmd-Shift-4 — selection screenshot
"Press command shift five keys"         # Cmd-Shift-5 — screenshot toolbar

## UNDO AND REDO
"Undo that" / "Undo"                    # Undo last action
"Redo that" / "Redo"                    # Redo

## MOVING AROUND A DOCUMENT
"Move up <n> lines"                     # Cursor up n lines
"Move down <n> lines"                   # Cursor down n lines
"Move left <n> characters"              # Cursor left n characters
"Move right <n> words"                  # Cursor right n words
"Move to beginning" / "Move to start"   # Start of document
"Move to end"                           # End of document
"Move to beginning of line"             # Start of current line
"Move to end of line"                   # End of current line
"Go to <word>"                          # Jump cursor to a specific word

## SELECTING TEXT
"Select <word>"                         # Select a specific word (e.g. "Select beautiful")
"Select previous <n> words"             # Select n words back
"Select next <n> characters"            # Select n characters forward
"Select previous sentence"              # Select preceding sentence
"Select next paragraph"                 # Select following paragraph
"Select all"                            # Select everything
"Unselect that" / "Deselect that"       # Clear selection
"Extend selection back <n> words"       # Grow selection backward
"Extend selection <n> sentences"        # Grow selection forward by sentences

## CORRECTING TEXT
"Correct <word>"                        # Show alternatives for a word (e.g. "Correct elephant")
"Correct that"                          # Show alternatives for last phrase
"Replace <a> with <b>"                  # Substitute text (e.g. "Replace cool with awesome")
"Insert <text> before <word>"           # Insert before a word (e.g. "Insert cool before animals")
"Insert <text> after <word>"            # Insert after a word
"Delete that"                           # Delete last dictation
"Delete previous <n> characters"        # Delete n characters back
"Delete previous <n> words"             # Delete n words back
"Capitalize <word>"                     # Capitalize first letter
"Uppercase <word>"                      # ALL CAPS the word
"Lowercase <word>"                      # Lowercase the word
"Bold <word>" / "Italicize <word>"      # Style selected or named text
"Underline <word>"                      # Underline selected or named text

## DISCOVERY
"Show commands" / "Show me what to say" # Open the full command list for the current context
